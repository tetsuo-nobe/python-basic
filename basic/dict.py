'''
Python の基本
辞書型の例
'''

# 辞書型データ (名前と値をペアにしたデータ)の定義 
item1 = {
 '商品名':'りんご',
 'カテゴリ':'果物',
 '単価':150,
}

# 辞書型データから値を取得
item_name = item1['商品名']
item_price = item1['単価']

# 値を表示（数値は str 関数で文字に変換）
print(item_name + ' の単価は ' + str(item_price) + '円です。')

# 辞書型の中に辞書型のデータが存在するケース
item2 = {
 '商品名':'りんご',
 'カテゴリ':'果物',
 '単価':150,
 '仕入先':{
   '仕入先コード':1001,
   '仕入先名':'田中商店'
 }
}

# 辞書型データから値を取得（田中商店が表示される）
print(item2['仕入先']['仕入先名'])

# 辞書型の中に辞書型のデータと list型のデータが存在するケース
item3 = {
 '商品名':'りんご',
 'カテゴリ':'果物',
 '単価':150,
 '仕入先':{
   '仕入先コード':1001,
   '仕入先名':'田中商店'
 },
 '関連商品':['みかん','バナナ','スイカ']
}

# リスト型データから値を取得（バナナが表示される）
print(item3['関連商品'][1])

# --- get() メソッドを使った値の取得 ---

item4 = {
 '商品名':'みかん',
 'カテゴリ':'果物',
 '単価':100,
}

# get() はキーが存在しない場合にエラーにならず None を返す
# item1['産地'] はエラーになるが、item1.get('産地') は None を返す
print(item4.get('商品名'))   # りんご
print(item4.get('産地'))     # None（キーが存在しないため）

# get() の第2引数にデフォルト値を指定できる
print(item4.get('産地', '不明'))  # 不明（キーが存在しないためデフォルト値が返る）

# --- get() を連結して、入れ子の辞書型データから安全に値を取得する ---

item5 = {
 '商品名': 'りんご',
 '仕入先': {
   '仕入先名': '田中商店',
   '所在地': {
     '都道府県': '東京都',
     '市区町村': '千代田区'
   }
 }
}

# get().get().get() で入れ子の辞書を順番にたどる
# 「東京都」が表示される
print(item5.get('仕入先').get('所在地').get('都道府県'))

# 「千代田区」が表示される
print(item5.get('仕入先').get('所在地').get('市区町村'))

# 存在しないキーを途中で指定すると None が返るため、
# そのまま連結するとエラーになる点に注意
# 例: item4.get('製造元').get('所在地') → エラー（None に get() はない）

# 安全に連結するには、途中のデフォルト値に空の辞書 {} を指定する
# キー '製造元' は存在しないが、デフォルト値 {} が返るので連結してもエラーにならない
result = item5.get('製造元', {}).get('所在地', {}).get('都道府県', '情報なし')
print(result)  # 情報なし

